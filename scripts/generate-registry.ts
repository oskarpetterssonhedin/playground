/**
 * Scans app/prototypes/* and writes two gitignored files:
 *
 *   lib/registry.generated.ts  metadata + thumbnail URLs for every prototype
 *                              (safe to import anywhere, including proxy.ts)
 *   lib/loaders.generated.ts   lazy page imports for PUBLIC prototypes only
 *                              (used by /p/[slug]; private code never ships there)
 *
 * Fails loudly when a prototype folder is incomplete or its metadata is invalid.
 * Runs automatically before dev, build, typecheck and after install.
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { prototypeMetadataSchema, SLUG_PATTERN, type Prototype } from "../lib/prototype-schema";

const ROOT = path.resolve(__dirname, "..");
const PROTOTYPES_DIR = path.join(ROOT, "app", "prototypes");
const THUMBS_DIR = path.join(ROOT, "public", "thumbnails");
const REQUIRED_FILES = ["page.tsx", "metadata.json", "HOW_IT_WORKS.md"];
const THUMB_EXTENSIONS = ["webp", "png"];

function thumbnailUrl(slug: string, variant: "light" | "dark" | "og"): string | null {
  for (const ext of variant === "og" ? ["jpg"] : THUMB_EXTENSIONS) {
    const file = path.join(THUMBS_DIR, `${slug}-${variant}.${ext}`);
    if (existsSync(file)) {
      const hash = createHash("sha1").update(readFileSync(file)).digest("hex").slice(0, 8);
      return `/thumbnails/${slug}-${variant}.${ext}?v=${hash}`;
    }
  }
  return null;
}

function collect(): Prototype[] {
  const errors: string[] = [];
  const prototypes: Prototype[] = [];

  const entries = existsSync(PROTOTYPES_DIR)
    ? readdirSync(PROTOTYPES_DIR, { withFileTypes: true })
    : [];

  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name.startsWith("_") || entry.name.startsWith(".")) continue;
    const slug = entry.name;
    const dir = path.join(PROTOTYPES_DIR, slug);

    if (!SLUG_PATTERN.test(slug)) {
      errors.push(`${slug}: folder name must be kebab-case (a-z, 0-9, hyphens)`);
      continue;
    }
    const missing = REQUIRED_FILES.filter((f) => !existsSync(path.join(dir, f)));
    if (missing.length) {
      errors.push(`${slug}: missing ${missing.join(", ")}`);
      continue;
    }

    let raw: unknown;
    try {
      raw = JSON.parse(readFileSync(path.join(dir, "metadata.json"), "utf8"));
    } catch (e) {
      errors.push(`${slug}: metadata.json is not valid JSON (${(e as Error).message})`);
      continue;
    }
    const parsed = prototypeMetadataSchema.safeParse(raw);
    if (!parsed.success) {
      const issues = parsed.error.issues.map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`);
      errors.push(`${slug}: invalid metadata.json\n    ${issues.join("\n    ")}`);
      continue;
    }

    prototypes.push({
      slug,
      ...parsed.data,
      thumbnails: {
        light: thumbnailUrl(slug, "light"),
        dark: thumbnailUrl(slug, "dark"),
        og: thumbnailUrl(slug, "og"),
      },
    });
  }

  if (errors.length) {
    console.error(`\n✖ Prototype registry errors:\n  ${errors.join("\n  ")}\n`);
    process.exit(1);
  }

  return prototypes.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
}

function write(prototypes: Prototype[]) {
  const header = "// AUTO-GENERATED by scripts/generate-registry.ts. Do not edit. Gitignored.\n";

  const registry =
    header +
    `import type { Prototype } from "./prototype-schema";\n\n` +
    `export const prototypes: Prototype[] = ${JSON.stringify(prototypes, null, 2)};\n\n` +
    `export const publicSlugs: string[] = ${JSON.stringify(
      prototypes.filter((p) => p.public).map((p) => p.slug),
    )};\n`;

  const publicOnes = prototypes.filter((p) => p.public);
  const loaders =
    header +
    `import type { ComponentType } from "react";\n\n` +
    `export const publicLoaders: Record<string, () => Promise<{ default: ComponentType }>> = {\n` +
    publicOnes.map((p) => `  ${JSON.stringify(p.slug)}: () => import("@/app/prototypes/${p.slug}/page"),\n`).join("") +
    `};\n`;

  writeIfChanged(path.join(ROOT, "lib", "registry.generated.ts"), registry);
  writeIfChanged(path.join(ROOT, "lib", "loaders.generated.ts"), loaders);
}

function writeIfChanged(file: string, content: string) {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  writeFileSync(file, content);
}

const prototypes = collect();
write(prototypes);
console.log(
  `✓ Registry: ${prototypes.length} prototype(s), ${prototypes.filter((p) => p.public).length} public`,
);
